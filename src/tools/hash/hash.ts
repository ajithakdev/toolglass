/** Incremental SHA-3 (domain 0x06) or original Keccak (domain 0x01) sponge. */
export function keccak(bits: number, domain: 0x06 | 0x01) {
  const rate = 200 - bits / 4;
  const state = new Int32Array(50);
  const bytes = new Uint8Array(state.buffer); // little-endian on every platform browsers run on
  let pos = 0;
  const absorb = (data: Uint8Array) => {
    let i = 0;
    const len = data.length;
    while (i < len) {
      // Fast path: whole 32-bit words while aligned (rate is a multiple of 8)
      if ((pos & 3) === 0) {
        while (i + 4 <= len && pos < rate) {
          state[pos >> 2] ^= data[i]! | (data[i + 1]! << 8) | (data[i + 2]! << 16) | (data[i + 3]! << 24);
          pos += 4;
          i += 4;
        }
      }
      while (i < len && pos < rate && (i + 4 > len || (pos & 3) !== 0)) bytes[pos++]! ^= data[i++]!;
      if (pos === rate) {
        permute(state);
        pos = 0;
      }
    }
  };
  return {
    update(data: Uint8Array) {
      absorb(data);
    },
    digest(): string {
      bytes[pos]! ^= domain;
      bytes[rate - 1]! ^= 0x80;
      permute(state);
      return toHex(bytes.slice(0, bits / 8));
    },
  };
}

function sponge(algo: Algo) {
  if (algo === 'Keccak-256') return keccak(256, 0x01);
  return algo.startsWith('SHA3-') ? keccak(Number(algo.slice(5)), 0x06) : null;
}

export async function hashBytes(data: Uint8Array<ArrayBuffer>, algo: Algo): Promise<string> {
  const k = sponge(algo);
  if (k) {
    k.update(data);
    return k.digest();
  }
  return toHex(new Uint8Array(await crypto.subtle.digest(algo, data)));
}

export const hashText = (text: string, algo: Algo) => hashBytes(new TextEncoder().encode(text), algo);

/**
 * Every algorithm for one file. Streams the file once: SHA-3 variants absorb chunk by chunk,
 * and the chunks fill one buffer for WebCrypto, which has no streaming digest.
 * shortcut: holds the whole file in memory for SHA-1/2; fine to a few GB, swap in a streaming SHA-2 if people need more.
 */
export async function hashFile(file: Blob, onProgress?: (fraction: number) => void): Promise<Record<Algo, string>> {
  const all = new Uint8Array(file.size);
  const sponges = ALGOS.map((a) => [a, sponge(a)] as const).filter((e) => e[1]);
  const reader = file.stream().getReader();
  let read = 0;
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    all.set(value, read);
    read += value.length;
    sponges.forEach(([, k]) => k!.update(value));
    onProgress?.(file.size ? read / file.size : 1);
  }
  const out = {} as Record<Algo, string>;
  for (const a of ALGOS) {
    const k = sponges.find(([s]) => s === a)?.[1];
    out[a] = k ? k.digest() : await hashBytes(all, a);
  }
  return out;
}
