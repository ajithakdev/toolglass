// Keccak-f[1600] round constants as low, high 32-bit pairs, generated as in FIPS 202 §3.2.5
const RC: number[] = [];
for (let i = 0, r = 1; i < 24; i++) {
  let lo = 0, hi = 0;
  for (let j = 0; j < 7; j++) {
    if (r & 1) {
      const bit = (1 << j) - 1;
      if (bit < 32) lo ^= 1 << bit;
      else hi ^= 1 << (bit - 32);
    }
    r = r & 0x80 ? ((r << 1) ^ 0x71) & 0xff : r << 1;
  }
  RC.push(lo, hi);
}

